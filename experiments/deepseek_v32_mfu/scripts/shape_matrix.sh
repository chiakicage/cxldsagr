#!/usr/bin/env bash
set -euo pipefail
script_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
cd -- "$script_dir/../../.."
export PATH="$PWD/.venv/bin:$PATH"
export PYTHONDONTWRITEBYTECODE=1
export DG_JIT_WITH_LINEINFO=1

usage() {
  cat <<'EOF'
Usage: shape_matrix.sh [matrix options] [-- common measurement options]

Sequentially run independent check, bench, minimal node profile, and timelines
for H=[4096,16384,65536] x A=[128,256,512,1024]. Every shape uses three real
checkpoint layers, cold full-extend CUDA Graph replay, history chunk 1024,
extend chunk A, and P=NH=H+A. Startup timelines are also generated by default.

Matrix options:
  --prefix-tokens LIST    Comma-separated subset of 4096,16384,65536
  --extend-tokens LIST    Comma-separated subset of 128,256,512,1024
  --trace-warmups N       Warmups per profile capture (default: 1)
  --no-startup           Omit the additional extend-startup timelines
  -h, --help             Show this help without creating outputs

Common options: --model, --physical-device, --warmups, --repeats,
  --prefill-repeats, --seed, --workspace-query-tokens,
  --hbm-cache-budget-gib, --dram-cache-budget-gib.
All other execution and output options are owned by this script.

Set MFU_RUN_ID to a fresh matrix ID; the default includes a UTC timestamp.
Child IDs: <matrix-id>_h<H>_a<A>_{check,bench,profile,timeline,startup}.
Check receipts remain under ${TMPDIR:-/tmp}/cxldsagr-checks/deepseek_v32_mfu.
Successful measurement/timeline outputs remain in output/{data,log,profile}.
The completed manifest is output/data/<matrix-id>/manifest.json. Report
generation is a separate step. Any child failure stops the matrix immediately;
completed child runs remain valid and diagnostics stay outside experiments.

Example (run from the repository root):
  MFU_RUN_ID=deepseek_shape_matrix_new CUDA_VISIBLE_DEVICES=3 taskset -c 24-31 \
    bash experiments/deepseek_v32_mfu/scripts/shape_matrix.sh -- \
    --physical-device 3 --model /preset-models
EOF
}

invocation=("$0" "$@")
prefix_spec=4096,16384,65536
extend_spec=128,256,512,1024
trace_warmups=1
startup=true
common=()
while (($#)); do
  case "$1" in
    -h|--help) usage; exit 0 ;;
    --prefix-tokens|--extend-tokens|--trace-warmups)
      if (($# < 2)); then echo "Missing value for $1" >&2; exit 2; fi
      case "$1" in
        --prefix-tokens) prefix_spec="$2" ;;
        --extend-tokens) extend_spec="$2" ;;
        --trace-warmups) trace_warmups="$2" ;;
      esac
      shift 2 ;;
    --prefix-tokens=*) prefix_spec="${1#*=}"; shift ;;
    --extend-tokens=*) extend_spec="${1#*=}"; shift ;;
    --trace-warmups=*) trace_warmups="${1#*=}"; shift ;;
    --no-startup) startup=false; shift ;;
    --) shift; common+=("$@"); break ;;
    *) common+=("$1"); shift ;;
  esac
done

validate_list() {
  local name="$1" specification="$2" allowed="$3" value
  if [[ ! "$specification" =~ ^[1-9][0-9]*(,[1-9][0-9]*)*$ ]]; then
    echo "$name must be a comma-separated list of token counts" >&2; exit 2
  fi
  local -A seen=()
  local -a values=()
  IFS=, read -r -a values <<< "$specification"
  for value in "${values[@]}"; do
    if [[ ",$allowed," != *",$value,"* || -n "${seen[$value]:-}" ]]; then
      echo "$name must be a subset of $allowed without duplicates" >&2; exit 2
    fi
    seen[$value]=1
  done
}
validate_list --prefix-tokens "$prefix_spec" 4096,16384,65536
validate_list --extend-tokens "$extend_spec" 128,256,512,1024
if [[ ! "$trace_warmups" =~ ^(0|[1-9][0-9]*)$ ]]; then
  echo "--trace-warmups must be a nonnegative integer" >&2; exit 2
fi
IFS=, read -r -a prefixes <<< "$prefix_spec"
IFS=, read -r -a extensions <<< "$extend_spec"

# Restrict forwarding so no child can silently override a matrix-owned shape,
# receipt, graph/residency policy, request, or publication destination.
index=0
while ((index < ${#common[@]})); do
  argument="${common[$index]}"
  case "${argument%%=*}" in
    --model|--physical-device|--warmups|--repeats|--prefill-repeats|--seed|--workspace-query-tokens|--hbm-cache-budget-gib|--dram-cache-budget-gib)
      if [[ "$argument" != *=* ]]; then
        index=$((index + 1))
        if ((index == ${#common[@]})) || [[ "${common[$index]}" == --* ]]; then
          echo "Missing value for $argument" >&2; exit 2
        fi
      elif [[ -z "${argument#*=}" ]]; then
        echo "Missing value for ${argument%%=*}" >&2; exit 2
      fi ;;
    *) echo "Unsupported or matrix-owned option: $argument (see --help)" >&2; exit 2 ;;
  esac
  index=$((index + 1))
done

run_id="${MFU_RUN_ID:-$(date -u +%Y%m%dT%H%M%S%NZ)_mfu_shape_matrix}"
if [[ ! "$run_id" =~ ^[A-Za-z0-9][A-Za-z0-9._-]*$ ]]; then
  echo "Invalid MFU_RUN_ID" >&2; exit 2
fi
base="experiments/deepseek_v32_mfu/output"
check_base="${TMPDIR:-/tmp}/cxldsagr-checks/deepseek_v32_mfu"
require_fresh() {
  local root="$1" id="$2" category
  for category in data log profile; do
    if [[ -e "$root/$category/$id" || -L "$root/$category/$id" ]]; then
      echo "Run output already exists: $root/$category/$id" >&2; exit 2
    fi
  done
}
require_fresh "$base" "$run_id"
for prefix in "${prefixes[@]}"; do
  for extend in "${extensions[@]}"; do
    shape_id="${run_id}_h${prefix}_a${extend}"
    require_fresh "$check_base" "${shape_id}_check"
    for phase in bench profile timeline; do require_fresh "$base" "${shape_id}_${phase}"; done
    if [[ "$startup" == true ]]; then require_fresh "$base" "${shape_id}_startup"; fi
  done
done

staging="$(mktemp -d "${TMPDIR:-/tmp}/deepseek-matrix-${run_id}.XXXXXX")"
mkdir "$staging/data" "$staging/log" "$staging/profile"
published=false
claimed=()
finish() {
  local status=$?
  if [[ "$published" != true ]]; then
    for path in "${claimed[@]}"; do rm -rf -- "$path"; done
    echo "Matrix stopped (status $status); diagnostics: $staging" >&2
  fi
}
trap finish EXIT
trap 'exit 130' INT
trap 'exit 143' TERM

python - "$staging/data/manifest.json" "$run_id" "$prefix_spec" "$extend_spec" \
  "$startup" "$trace_warmups" "$script_dir/shape_matrix.sh" "${invocation[@]}" <<'PY'
import datetime
import hashlib
import json
import sys
from pathlib import Path

destination, run_id, prefixes, extensions, startup, warmups, source, *invocation = sys.argv[1:]
manifest = {
    "schema_version": 1,
    "run_id": run_id,
    "started_at_utc": datetime.datetime.now(datetime.timezone.utc).isoformat(),
    "configuration": {
        "prefix_tokens": [int(value) for value in prefixes.split(",")],
        "extend_tokens": [int(value) for value in extensions.split(",")],
        "history_chunk_tokens": 1024,
        "extend_chunk_tokens": "A",
        "pool_tokens": "H+A",
        "host_tokens": "H+A",
        "extend_residency": "cold",
        "extend_graph": True,
        "startup_timeline": startup == "true",
        "trace_warmups": int(warmups),
    },
    "runner": {
        "source": str(Path(source).relative_to(Path.cwd())),
        "sha256": hashlib.sha256(Path(source).read_bytes()).hexdigest(),
        "invocation": invocation,
    },
    "shapes": [],
}
Path(destination).write_text(json.dumps(manifest, indent=2) + "\n")
PY

render_timeline() {
  local id="$1" window="$2" profile_run="$3" category
  mkdir "$staging/log/$id"
  CUDA_VISIBLE_DEVICES= python -m experiments.deepseek_v32_mfu.src.compact_timeline \
    --profile-run "$profile_run" --gap-audit "$profile_run/gap_audit.json" \
    --output-dir "$staging/$id" --layout separate --window "$window" \
    --io-layout directions --annotations idle-echo \
    >"$staging/log/$id/stdout.log" 2>"$staging/log/$id/stderr.log"
  for category in data log profile; do
    mkdir -p "$base/$category"
    mkdir "$base/$category/$id"
    claimed+=("$base/$category/$id")
  done
  cp -a -- "$staging/$id/." "$base/data/$id/"
  cp -a -- "$staging/log/$id/." "$base/log/$id/"
  claimed=()
  rm -rf -- "$staging/$id" "$staging/log/$id"
}

for prefix in "${prefixes[@]}"; do
  for extend in "${extensions[@]}"; do
    shape_id="${run_id}_h${prefix}_a${extend}"
    check_run="$check_base/data/${shape_id}_check"
    bench_run="$base/data/${shape_id}_bench"
    profile_run="$base/data/${shape_id}_profile"
    shape=(--prefix "$prefix" --extend "$extend" --chunk-size 1024
      --extend-chunk-size "$extend" --sparse-pool-tokens "$((prefix + extend))"
      --host-arena-tokens "$((prefix + extend))" --compute-graphs --extend-graph
      --extend-residency cold "${common[@]}")
    echo "H=$prefix A=$extend: check"
    MFU_RUN_ID="${shape_id}_check" bash "$script_dir/run.sh" --mode check "${shape[@]}"
    echo "H=$prefix A=$extend: bench"
    MFU_RUN_ID="${shape_id}_bench" bash "$script_dir/run.sh" --mode bench "${shape[@]}" \
      --validation-receipt "$check_run/receipt.json"
    echo "H=$prefix A=$extend: profile"
    MFU_RUN_ID="${shape_id}_profile" bash "$script_dir/gap_profile.sh" "${shape[@]}" \
      --trace-warmups "$trace_warmups" --validation-receipt "$check_run/receipt.json" \
      --benchmark-run "$bench_run"
    echo "H=$prefix A=$extend: timelines"
    render_timeline "${shape_id}_timeline" three-layers "$profile_run"
    startup_run=""
    if [[ "$startup" == true ]]; then
      render_timeline "${shape_id}_startup" extend-startup "$profile_run"
      startup_run="$base/data/${shape_id}_startup"
    fi
    python - "$staging/data/manifest.json" "$prefix" "$extend" "$shape_id" \
      "$check_run" "$bench_run" "$profile_run" "$base/data/${shape_id}_timeline" \
      "$startup_run" <<'PY'
import hashlib
import json
import sys
from pathlib import Path

manifest_path, prefix, extend, shape_id, check, bench, profile, timeline, startup = sys.argv[1:]
path = Path(manifest_path)
manifest = json.loads(path.read_text())
row = {
    "prefix_tokens": int(prefix),
    "extend_tokens": int(extend),
    "pool_tokens": int(prefix) + int(extend),
    "host_tokens": int(prefix) + int(extend),
    "check_run_id": shape_id + "_check",
    "bench_run_id": shape_id + "_bench",
    "profile_run_id": shape_id + "_profile",
    "timeline_run_id": shape_id + "_timeline",
    "startup_run_id": shape_id + "_startup" if startup else None,
    "check_run": check,
    "bench_run": bench,
    "profile_run": profile,
    "timeline_run": timeline,
    "startup_run": startup or None,
    "validation_receipt_sha256": hashlib.sha256(
        (Path(check) / "receipt.json").read_bytes()
    ).hexdigest(),
}
manifest["shapes"].append(row)
path.write_text(json.dumps(manifest, indent=2) + "\n")
PY
  done
done

python - "$staging/data/manifest.json" <<'PY'
import datetime
import hashlib
import json
import sys
from pathlib import Path

path = Path(sys.argv[1])
manifest = json.loads(path.read_text())
config = manifest["configuration"]
expected = [(h, a) for h in config["prefix_tokens"] for a in config["extend_tokens"]]
actual = [(row["prefix_tokens"], row["extend_tokens"]) for row in manifest["shapes"]]
if actual != expected:
    raise ValueError("Matrix does not contain all requested shapes in execution order")
runner = manifest["runner"]
if hashlib.sha256(Path(runner["source"]).read_bytes()).hexdigest() != runner["sha256"]:
    raise ValueError("Matrix runner changed during execution")
manifest["completed_at_utc"] = datetime.datetime.now(datetime.timezone.utc).isoformat()
path.write_text(json.dumps(manifest, indent=2) + "\n")
PY
for category in data log profile; do
  mkdir -p "$base/$category"
  mkdir "$base/$category/$run_id"
  claimed+=("$base/$category/$run_id")
  cp -a -- "$staging/$category/." "$base/$category/$run_id/"
done
published=true
rm -rf -- "$staging"
echo "Completed matrix: $base/data/$run_id/manifest.json"
